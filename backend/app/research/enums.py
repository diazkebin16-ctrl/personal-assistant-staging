    RATE_LIMITED = "RESEARCH_RATE_LIMITED"
    SEARCH_TIMEOUT = "RESEARCH_SEARCH_TIMEOUT"
    FETCH_TIMEOUT = "RESEARCH_FETCH_TIMEOUT"
    BLOCKED_URL = "RESEARCH_BLOCKED_URL"
    DNS_REBINDING = "RESEARCH_DNS_REBINDING"
    UNSUPPORTED_CONTENT = "RESEARCH_UNSUPPORTED_CONTENT"
    CONTENT_TOO_LARGE = "RESEARCH_CONTENT_TOO_LARGE"
    EXTRACTION_FAILED = "RESEARCH_EXTRACTION_FAILED"
    INSUFFICIENT_EVIDENCE = "RESEARCH_INSUFFICIENT_EVIDENCE"
    CITATION_INTEGRITY = "RESEARCH_CITATION_INTEGRITY"
    MALFORMED_SYNTHESIS = "RESEARCH_MALFORMED_SYNTHESIS"
