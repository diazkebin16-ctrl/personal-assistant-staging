    POLICY_DENIED = "RESEARCH_POLICY_DENIED"
    PERMISSION_REQUIRED = "RESEARCH_PERMISSION_REQUIRED"
    CONFIRMATION_REQUIRED = "RESEARCH_CONFIRMATION_REQUIRED"
